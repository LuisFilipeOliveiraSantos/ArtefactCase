"""Run the example conversations against the real agent and save them to examples/*.md.

    uv run python scripts/run_examples.py            # all scenarios
    uv run python scripts/run_examples.py 03         # only scenarios whose file starts with "03"

Needs GEMINI_API_KEY (or another provider) in .env. Each file records the customer messages, the tools the agent
called (with arguments) and the agent's replies, exactly as returned.
"""

