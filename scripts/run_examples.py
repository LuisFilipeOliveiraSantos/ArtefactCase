def render(scenario: dict, transcript: list[tuple[str, str, list]], model: str) -> str:
    when = datetime.now(STORE_TZ).strftime("%Y-%m-%d %H:%M")
    lines = [
        f"# {scenario['title']}",
        "",
        f"_Generated by `scripts/run_examples.py` on {when} (Campo Grande time) with `{model}`._",
        "",
    ]
    for user, reply, calls in transcript:
        lines += [f"**Customer:** {user}", ""]
        if calls:
            lines += ["<details><summary>Tools called</summary>", "", "```"]
            lines += [f"{c.name}({json.dumps(c.arguments, ensure_ascii=False)})" for c in calls]
            lines += ["```", "", "</details>", ""]
        quoted = "\n".join(f"> {line}" if line else ">" for line in reply.splitlines())
        lines += ["**Agent:**", "", quoted, "", "---", ""]
    return "\n".join(lines)


def main() -> None:
    load_dotenv()
    prefix = sys.argv[1] if len(sys.argv) > 1 else ""
    for scenario in SCENARIOS:
        if not scenario["file"].startswith(prefix):
            continue
        agent = Agent()
        transcript = []
        print(f"== {scenario['file']}")
        for user in scenario["turns"]:
            reply, calls = agent.reply(user)
            print(f"> {user}\n  tools: {[c.name for c in calls]}\n{reply}\n")
            transcript.append((user, reply, calls))
        (EXAMPLES_DIR / scenario["file"]).write_text(render(scenario, transcript, agent.model), encoding="utf-8")


if __name__ == "__main__":
    main()
